"""
Reference / calibration cohort.

A deterministic (seed=42) simulated cohort of 400 labelled candidate-job cases is generated by
creating a latent 'true' skill set, then writing a noisy resume (aliases, inflated mentions,
unrelated buzzwords). Ground truth:  suitable = true weighted coverage >= 0.6 AND education met
AND experience >= 60% of requirement.
  * cases 0-199   calibration -> empirical conditional-probability table
  * cases 200-399 validation  -> hypothesis test (proposed algorithm vs literal keyword matching)
  * all cases     -> reference distribution of resume-quality scores (Gaussian analysis)
Limitation: simulated data demonstrates the statistics; replace with real hiring outcomes in production.
"""
import random
from functools import lru_cache

import numpy as np
from sklearn.linear_model import LogisticRegression

from ..algorithms import conditional_probability as cond, hypothesis_testing as ht
from . import scoring
from .resume_parser import skill_weights
from .seed import SEED_JOBS
from .skills_taxonomy import TAXONOMY

N_CASES, N_CAL = 400, 200


@lru_cache(maxsize=1)
def get_reference() -> dict:
    rng = random.Random(42)
    jobs = [scoring.job_from_seed(j, i) for i, j in enumerate(SEED_JOBS)]
    names = list(TAXONOMY)
    cases = []
    for _ in range(N_CASES):
        job = rng.choice(jobs)
        competence = rng.betavariate(2, 2)
        p_have = 0.15 + 0.8 * competence
        has = {s: rng.random() < p_have for s in job["requirements"]}
        tot = sum(job["requirements"].values())
        true_cov = sum(job["requirements"][s] for s, h in has.items() if h) / tot
        years = rng.choice([0, 0, 0.5, 1, 1, 2, 3, 4, 6, 8])
        edu = rng.choice([1, 2, 2, 2, 3, 3, 4])
        mentioned = [job["names"][s] for s, h in has.items() if (h and rng.random() < 0.85) or (not h and rng.random() < 0.12)]
        mentioned += rng.sample(names, rng.randint(2, 5))
        listed, shown = [], []
        for m in dict.fromkeys(mentioned):
            term = m if rng.random() < 0.5 or m not in TAXONOMY else rng.choice(TAXONOMY[m]["aliases"])
            (shown if rng.random() < 0.55 else listed).append(term)
        skills_text = "Skills: " + ", ".join(listed)
        evidence_text = " ".join(f"Built features using {t}." for t in shown)
        text = (skills_text + "\n" + evidence_text).lower()
        weights = skill_weights(skills_text, evidence_text)
        cand = scoring.make_candidate(weights, edu, years, n_certs=rng.randint(0, 3), n_projects=rng.randint(0, 4),
                                      has_summary=rng.random() < 0.7)
        f = scoring.features(cand, job)
        label = (true_cov >= 0.6) and f["edu_ok"] and (job["min_exp"] == 0 or years >= 0.6 * job["min_exp"])
        base = sum(1 for s in job["requirements"] if s in text) / len(job["requirements"])   # literal keyword match
        cases.append({"cand": cand, "job": job, "coverage": f["coverage"], "edu_ok": f["edu_ok"], "exp_ok": f["exp_ok"],
                      "label": bool(label), "baseline": base})
    table = cond.fit(cases[:N_CAL])
    for c in cases:  # raw scores of both methods, in [0,1]
        c["proposed"] = scoring.evaluate(c["cand"], c["job"], jobs, table)["compatibility"] / 100
    # Raw scores live on different scales, so each method's score is mapped to a probability with a
    # 1-D logistic calibration fitted on the calibration split only (fair to both methods).
    y_cal = [int(c["label"]) for c in cases[:N_CAL]]
    val = cases[N_CAL:]

    def calibrated(key):
        lr = LogisticRegression(C=100.0).fit(np.array([[c[key]] for c in cases[:N_CAL]]), y_cal)
        return lr.predict_proba(np.array([[c[key]] for c in val]))[:, 1]

    result = ht.compare_methods([int(c["label"]) for c in val], calibrated("proposed"), calibrated("baseline"), threshold=0.5)
    result["n_calibration"], result["n_validation"] = N_CAL, len(val)
    result["positive_rate"] = float(sum(c["label"] for c in val) / len(val))
    result["calibration"] = "Both scores mapped to probabilities by logistic regression fitted on the calibration split"
    return {"table": table, "quality_scores": [scoring.resume_quality(c["cand"])[0] for c in cases], "hypothesis": result}
